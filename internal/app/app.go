package app

import (
	"fmt"

	"app/internal/core/config"
	"app/internal/features/auth"
	"app/internal/features/user"
	"app/internal/shared/delivery/http/apidocs"
	"app/internal/shared/delivery/http/middleware"
	"app/internal/shared/delivery/http/webui"
	"app/internal/shared/infrastructure/database"
	"app/internal/shared/infrastructure/database/migrator"
	sharedRepo "app/internal/shared/infrastructure/repository"
	"app/migrations"
	"app/pkg/logger"

	"github.com/gin-gonic/gin"
	"github.com/sirupsen/logrus"
)

// Feature defines the interface that each feature module must implement
type Feature interface {
	// Name returns the feature name for logging/debugging
	Name() string
	// RegisterRoutes registers all routes for this feature
	// rg: the base router group (/api/v1)
	RegisterRoutes(rg *gin.RouterGroup)
}

// App holds the application and its dependencies
type App struct {
	Config *config.Config
	DB     *database.PostgresDB
	Engine *gin.Engine
	Logger *logrus.Logger
}

// New creates and initializes the application
func New() (*App, error) {
	app := &App{}

	// Load and validate configuration once; it is injected into every component.
	// Fails fast on unsafe values (e.g. a missing JWT_SECRET outside development).
	cfg, err := config.Load()
	if err != nil {
		return nil, fmt.Errorf("invalid configuration: %w", err)
	}
	app.Config = cfg

	app.Logger = logger.NewLogger()

	// Initialize database
	db, err := database.NewPostgresDB(cfg.Database)
	if err != nil {
		return nil, err
	}
	app.DB = db

	// Refuse to start when the schema does not match the embedded migrations
	sqlDB, err := db.GetDB().DB()
	if err != nil {
		db.Close()
		return nil, err
	}
	if err := migrator.CheckSchema(sqlDB, migrations.FS); err != nil {
		db.Close()
		return nil, err
	}

	// Setup router with features
	app.Engine = app.setupRouter()

	return app, nil
}

// setupRouter configures the HTTP router and registers all features
func (a *App) setupRouter() *gin.Engine {
	gin.SetMode(gin.ReleaseMode)
	router := gin.New()

	// Global middleware
	router.Use(middleware.LoggerMiddleware())
	router.Use(gin.Recovery())
	router.Use(middleware.CORSMiddleware(a.Config.CORS.AllowedOrigins))
	router.Use(middleware.LanguageMiddleware())

	// Health check endpoint
	router.GET("/health", func(c *gin.Context) {
		c.JSON(200, gin.H{
			"status":  "ok",
			"message": "Service is running",
		})
	})

	// API v1 routes
	v1 := router.Group("/api/v1")

	// Initialize shared repository
	userRepo := sharedRepo.NewUserRepository(a.DB.GetDB())

	// Register all features - just add one line per new feature!
	features := []Feature{
		auth.NewModule(userRepo, a.Logger, a.Config.JWT.Secret),
		user.NewModule(userRepo, a.Logger, a.Config.JWT.Secret),
	}

	for _, f := range features {
		f.RegisterRoutes(v1)
	}

	// API documentation (Scalar UI + OpenAPI spec generated by swag)
	apidocs.RegisterRoutes(router)

	// SPA frontend (embedded build of /frontend). Must stay last: it owns NoRoute.
	webui.RegisterRoutes(router)

	return router
}

// Close releases all resources held by the application
func (a *App) Close() error {
	if a.DB != nil {
		return a.DB.Close()
	}
	return nil
}
